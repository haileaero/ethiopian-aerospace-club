-- Ethiopian Aerospace Club authentication + profile foundation
-- Run this entire file in Supabase SQL Editor after creating a Supabase project.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  username text unique,
  membership_type text not null default 'Student',
  affiliation text,
  department text,
  year text,
  profession text,
  interests text,
  preferred_contribution text,
  phone text,
  role text not null default 'member' check (role in ('member','admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles add column if not exists preferred_contribution text;

alter table public.profiles enable row level security;

drop policy if exists "Users can view their own profile" on public.profiles;
create policy "Users can view their own profile" on public.profiles
for select using (auth.uid() = id);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile" on public.profiles
for update using (auth.uid() = id) with check (auth.uid() = id and role = (select p.role from public.profiles p where p.id = auth.uid()));

-- Admins can read all profiles for future member-management features.
drop policy if exists "Admins can view profiles" on public.profiles;
create policy "Admins can view profiles" on public.profiles
for select using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, username, membership_type, affiliation, department, year, profession, interests, preferred_contribution, phone)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    nullif(new.raw_user_meta_data->>'username', ''),
    coalesce(nullif(new.raw_user_meta_data->>'membership_type', ''), 'Student'),
    nullif(new.raw_user_meta_data->>'affiliation', ''),
    nullif(new.raw_user_meta_data->>'department', ''),
    nullif(new.raw_user_meta_data->>'year', ''),
    nullif(new.raw_user_meta_data->>'profession', ''),
    nullif(new.raw_user_meta_data->>'interests', ''),
    nullif(new.raw_user_meta_data->>'preferred_contribution', ''),
    nullif(new.raw_user_meta_data->>'phone', '')
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Keep updated_at current.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
before update on public.profiles
for each row execute procedure public.set_updated_at();

-- Optional content tables for the next CMS phase. They are intentionally separated
-- from authentication so the website can already operate securely with member/admin roles.
create table if not exists public.site_settings (
  id bigint generated by default as identity primary key,
  tagline text,
  email text,
  phone text,
  location text,
  updated_at timestamptz not null default now()
);

create table if not exists public.hero_slides (
  id bigint generated by default as identity primary key,
  label text not null default '',
  title text not null default '',
  text text not null default '',
  image_url text,
  sort_order integer not null default 0,
  published boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.committee_members (
  id bigint generated by default as identity primary key,
  name text not null default '',
  position text not null default '',
  department text,
  year text,
  bio text,
  photo_url text,
  sort_order integer not null default 0,
  published boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.social_links (
  id bigint generated by default as identity primary key,
  platform text unique not null,
  url text not null,
  sort_order integer not null default 0,
  published boolean not null default true,
  updated_at timestamptz not null default now()
);

alter table public.site_settings enable row level security;
alter table public.hero_slides enable row level security;
alter table public.committee_members enable row level security;
alter table public.social_links enable row level security;

-- Public visitors can read published content.
drop policy if exists "Public can read site settings" on public.site_settings;
create policy "Public can read site settings" on public.site_settings for select using (true);
drop policy if exists "Public can read published hero slides" on public.hero_slides;
create policy "Public can read published hero slides" on public.hero_slides for select using (published = true);
drop policy if exists "Public can read published committee" on public.committee_members;
create policy "Public can read published committee" on public.committee_members for select using (published = true);
drop policy if exists "Public can read published social links" on public.social_links;
create policy "Public can read published social links" on public.social_links for select using (published = true);

